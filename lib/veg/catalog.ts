export type CatalogBed = {
  id: string;
  blockId: string;
  label: string;
  position: number;
  length: number;
  width: number;
  unit: Unit;
};

export function catalogBeds(): CatalogBed[] {
  return BLOCKS.flatMap((block) =>
    Array.from({ length: block.bedCount }, (_, position) => ({
      id: `bed_${block.bedPrefix.toLowerCase()}_${position + 1}`,
      blockId: block.id,
      label: `${block.bedPrefix}-${position + 1}`,
      position,
      length: block.bedLength,
      width: block.bedWidth,
      unit: block.unit,
    })),
  );
}

